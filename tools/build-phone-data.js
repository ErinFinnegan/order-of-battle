// Builds phone/data.js from the main app's catalog, an export of the shared database,
// and phone/curation.json.
//   node tools/build-phone-data.js <db-export-dir>
// <db-export-dir> holds ratings/, extra/ and about/ folders of JSON documents
// (one file per document, as the ArtifactData tool's out_dir writes them).
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "..");
const dbdir = process.argv[2];
if (!dbdir) { console.error("usage: node tools/build-phone-data.js <db-export-dir>"); process.exit(1); }

// Load the catalog and learning code straight out of the main app.
const html = fs.readFileSync(path.join(root, "src/artifact.html"), "utf8");
const js = html.split("<script>")[1].split("</script>")[0];
const engine = js.slice(js.indexOf("/* ---------- seed catalog"), js.indexOf("/* ---------- storage"));
const load = d => { const p = path.join(dbdir, d); if (!fs.existsSync(p)) return {};
  return Object.fromEntries(fs.readdirSync(p).filter(f => f.endsWith(".json")).map(f => {
    const j = JSON.parse(fs.readFileSync(path.join(p, f))); return [f.replace(/\.json$/, ""), j.data || j]; })); };
const E = new Function("RAT", "EXT", "ABT", engine + `
  state.ratings = RAT; state.extras = EXT; state.about = ABT; bust();
  return { books: allBooks(), status, feelOf, idOf, aboutOf };`)(load("ratings"), load("extra"), load("about"));

const cur = JSON.parse(fs.readFileSync(path.join(root, "phone/curation.json"), "utf8"));
const drop = new Set(cur.drop);
// Audiobook status from curation.json: audio = "yes" (with an Audible link) or "no".
const audioOf = id => { const a = cur.audio && cur.audio[id];
  return a ? { audio: "yes", audible: a.url || undefined, audioNote: a.note || undefined } : { audio: "no" }; };
const slim = b => ({ id: b.id, title: b.title, author: b.author, year: b.year || null, th: b.th, br: b.br, form: b.form,
  tags: b.tags || [], feel: b.feel || E.feelOf(b) || undefined, ...audioOf(b.id) });

// Everything he has answered: the phone app learns from it but never shows these books.
const history = E.books.filter(b => E.status(b.id)).map(b => {
  const h = { ...slim(b), s: E.status(b.id) };
  if (h.s === "unread") h.about = cur.about[b.id] || E.aboutOf(b) || "";   // shown on his Saved list
  return h;
});

// The shelf: unanswered books that survive the curation, plus new picks.
const shelf = E.books.filter(b => !E.status(b.id) && !drop.has(b.title))
  .map(b => ({ ...slim(b), about: cur.about[b.id] || E.aboutOf(b) || "" }));
const known = new Set(E.books.map(b => b.id));
for (const a of cur.add) {
  const b = { ...a, tags: a.tags || [] }; b.id = E.idOf(b);
  if (known.has(b.id)) { console.warn("already in catalog, skipped:", b.title); continue; }
  shelf.push({ ...slim(b), about: a.about, isNew: true });
}
const noAbout = shelf.filter(b => !b.about).map(b => b.title);
if (noAbout.length) console.warn("no description:", noAbout.join("; "));

const out = `// Generated by tools/build-phone-data.js on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
window.OOB_DATA = ${JSON.stringify({ built: new Date().toISOString().slice(0, 10), history, shelf })};
`;
fs.writeFileSync(path.join(root, "phone/data.js"), out);
console.log(`phone/data.js: ${history.length} answered, ${shelf.length} on the shelf (${cur.add.length} new)`);
